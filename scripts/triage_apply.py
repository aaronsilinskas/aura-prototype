"""Automated triage's apply step: validate Claude's decision and plan the GitHub writes for it.

Host-only (CPython), run by the triage workflow and never shipped. It is the only writer to
GitHub in the triage flow. :func:`plan` is pure: the triggering issue's :class:`IssueState`
and Claude's raw decision in, the operations to perform on that issue out, or none with the
reason why. :func:`perform` is the thin ``gh`` wrapper that carries them out, and ``main`` is
the workflow step's entry.
"""

import argparse
import json
import re
import subprocess
from collections.abc import Iterable, Sequence
from pathlib import Path
from typing import Final, NamedTuple

from scripts.triage import NEEDS_TRIAGE, IssueState, read_issue_state

# The JSON schema the workflow passes to Claude with --json-schema. plan() doesn't load it:
# it checks the same rules by hand, and a test keeps the schema's values and the maps below
# in step.
DECISION_SCHEMA: Final = Path(__file__).with_name("triage_decision.schema.json")

DISCLAIMER: Final = "> *This was generated by AI during triage.*"
MAX_COMMENT_LENGTH: Final = 8000

READY_FOR_AGENT: Final = "ready-for-agent"

# Canonical triage role -> label string, as docs/agents/triage-labels.md maps them.
CATEGORY_LABELS: Final = {"bug": "bug", "enhancement": "enhancement"}
STATE_LABELS: Final = {
    NEEDS_TRIAGE: "needs-triage",
    "needs-info": "needs-info",
    READY_FOR_AGENT: "ready-for-agent",
    "ready-for-human": "ready-for-human",
}
_TRIAGE_LABELS: Final = frozenset(CATEGORY_LABELS.values()) | frozenset(STATE_LABELS.values())

_REQUIRED_TEXT: Final = ("comment", "reasoning", "evidence")
_REQUIRED_FIELDS: Final = frozenset({"category", "state", "already_implemented", *_REQUIRED_TEXT})
_FIELDS: Final = _REQUIRED_FIELDS | {"agent_brief"}

# Token prefixes of the credentials a triage run could reach: Anthropic's, and GitHub's.
# Text carrying one is never posted, whether or not the token is live.
_CREDENTIAL: Final = re.compile(r"sk-ant-|gh[opsur]_|github_pat_", re.IGNORECASE)

_TRUNCATED: Final = "\n\n*(Truncated.)*"
# An @ that follows no word character, then a GitHub login; an email address's @ follows one.
_MENTION: Final = re.compile(r"(?<!\w)@([A-Za-z0-9][A-Za-z0-9-]*)")
# An issue or pull request reference GitHub links, and so cross-references on the target:
# #12, GH-12 and owner/repo#12 (the # or GH- part), and a .../issues/12, /pull/12 or
# /discussions/12 path, with or without the https://github.com/ in front.
_REFERENCE: Final = re.compile(r"(#|\bGH-|/(?:issues|pull|discussions)/)(?=\d)", re.IGNORECASE)
# Inside a mention or reference it stops GitHub linking it, and renders as nothing.
_ZERO_WIDTH_SPACE: Final = "\u200b"


class EditLabels(NamedTuple):
    """One ``gh issue edit``: the labels to add to an issue and the labels to remove from it."""

    issue_number: int
    add: frozenset[str]
    remove: frozenset[str]

    def gh_args(self) -> list[str]:
        args = ["gh", "issue", "edit", str(self.issue_number)]
        for label in sorted(self.add):
            args += ["--add-label", label]
        for label in sorted(self.remove):
            args += ["--remove-label", label]
        return args

    @property
    def stdin(self) -> None:
        return None

    def describe(self) -> str:
        return (
            f"labels on #{self.issue_number}: add {sorted(self.add)}, remove {sorted(self.remove)}"
        )


class PostComment(NamedTuple):
    """A comment to post; its body goes through stdin, so no text of Claude's is read as a flag."""

    issue_number: int
    body: str

    def gh_args(self) -> list[str]:
        return ["gh", "issue", "comment", str(self.issue_number), "--body-file", "-"]

    @property
    def stdin(self) -> str:
        return self.body

    def describe(self) -> str:
        return f"comment on #{self.issue_number} ({len(self.body)} characters)"


Operation = EditLabels | PostComment


class ApplyPlan(NamedTuple):
    """What to do on GitHub, and what to log.

    ``rejection`` is set exactly when the decision was invalid, and ``operations`` is then
    empty. ``reasoning`` is the decision's own, whenever it could be read.
    """

    operations: tuple[Operation, ...]
    rejection: str | None
    reasoning: str | None


class _InvalidDecisionError(Exception):
    pass


def plan(issue: IssueState, raw_decision: str | None) -> ApplyPlan:
    """Plan the writes for Claude's *raw_decision*: its JSON, or ``None`` if its step failed.

    Every operation targets *issue*, whatever the decision says. A valid decision yields one
    comment, then the label changes, if any: its category and state are added, and every
    other category and state role is removed. No other label is ever touched.

    The comment comes first so that a failed label edit leaves the issue on its old state
    (``needs-triage``, so still on the maintainer's list) with the triage comment posted,
    never on a new state without its comment: a ``ready-for-agent`` issue without its agent
    brief could be picked up by an agent.
    """
    decision: object = None
    try:
        if not raw_decision:
            raise _InvalidDecisionError("Claude produced no decision")
        try:
            decision = json.loads(raw_decision)
        except json.JSONDecodeError as error:
            raise _InvalidDecisionError(f"the decision is not valid JSON: {error}") from error
        operations = _operations(issue, decision)
    except _InvalidDecisionError as invalid:
        return ApplyPlan((), str(invalid), _reasoning(decision))
    return ApplyPlan(operations, None, _reasoning(decision))


def _reasoning(decision: object) -> str | None:
    if isinstance(decision, dict) and isinstance(decision.get("reasoning"), str):
        return decision["reasoning"]
    return None


def _operations(issue: IssueState, decision: object) -> tuple[Operation, ...]:
    if not isinstance(decision, dict):
        raise _InvalidDecisionError("the decision is not a JSON object")
    missing = _REQUIRED_FIELDS - decision.keys()
    if missing:
        raise _InvalidDecisionError(f"the decision is missing {sorted(missing)}")
    extra = decision.keys() - _FIELDS
    if extra:
        raise _InvalidDecisionError(f"the decision has unknown fields {sorted(extra)}")

    category = _label(CATEGORY_LABELS, decision["category"], "category")
    state = _label(STATE_LABELS, decision["state"], "state")
    if not isinstance(decision["already_implemented"], bool):
        raise _InvalidDecisionError("already_implemented is not a boolean")
    if decision["already_implemented"] and state != STATE_LABELS[NEEDS_TRIAGE]:
        raise _InvalidDecisionError(
            f"an already-implemented request must keep {NEEDS_TRIAGE!r}, not {state!r}"
        )
    for field in _REQUIRED_TEXT:
        if not _is_text(decision[field]):
            raise _InvalidDecisionError(f"{field} is not non-blank text")
    for field in _FIELDS:
        if _is_text(decision.get(field)) and _CREDENTIAL.search(decision[field]):
            raise _InvalidDecisionError(f"{field} carries a credential-shaped token")

    brief = decision.get("agent_brief")
    sections = [DISCLAIMER, decision["comment"]]
    if decision["state"] == READY_FOR_AGENT:
        if not _is_text(brief):
            raise _InvalidDecisionError(f"a {READY_FOR_AGENT!r} decision has no agent brief")
        sections.append(brief)
    elif brief is not None:
        raise _InvalidDecisionError(f"a {decision['state']!r} decision carries an agent brief")

    wanted = {category, state}
    comment = PostComment(issue.number, _shape_comment("\n\n".join(sections), issue.author))
    edit = EditLabels(
        issue.number,
        add=frozenset(wanted - issue.labels),
        remove=frozenset((_TRIAGE_LABELS - wanted) & issue.labels),
    )
    return (comment, edit) if edit.add or edit.remove else (comment,)


def _label(labels: dict[str, str], role: object, field: str) -> str:
    if not isinstance(role, str) or role not in labels:
        raise _InvalidDecisionError(f"{field} {role!r} is not one of {sorted(labels)}")
    return labels[role]


def _is_text(value: object) -> bool:
    return isinstance(value, str) and bool(value.strip())


def _shape_comment(body: str, author: str) -> str:
    """Neutralise every @-mention but the author's and every issue or pull request reference.

    Then cap *body* at :data:`MAX_COMMENT_LENGTH`. A reference would put a cross-reference
    on the target's timeline, in this repository or any other.
    """

    def neutralise(mention: re.Match[str]) -> str:
        is_author = mention[1].lower() == author.lower()
        is_team = body.startswith("/", mention.end())
        if is_author and not is_team:
            return mention[0]
        return "@" + _ZERO_WIDTH_SPACE + mention[1]

    body = _MENTION.sub(neutralise, body)
    body = _REFERENCE.sub(lambda reference: reference[1] + _ZERO_WIDTH_SPACE, body)
    if len(body) <= MAX_COMMENT_LENGTH:
        return body
    return body[: MAX_COMMENT_LENGTH - len(_TRUNCATED)] + _TRUNCATED


def perform(operations: Iterable[Operation]) -> None:
    """Carry out *operations* with ``gh``, in order; raises on the first ``gh`` failure."""
    for operation in operations:
        subprocess.run(operation.gh_args(), input=operation.stdin, text=True, check=True)


def _log(message: str, text: str) -> None:
    # json.dumps keeps Claude's text on one line, so it can never start a workflow command.
    print(f"triage apply: {message}: {json.dumps(text, ensure_ascii=False)}")


def main(argv: Sequence[str] | None = None) -> None:
    """Apply one decision to the triggering issue, logging the reasoning and any rejection.

    A missing or empty decision file means the Claude step produced no decision.
    """
    parser = argparse.ArgumentParser(description="Validate and apply Claude's triage decision.")
    parser.add_argument("--issue", required=True, type=int, help="the triggering issue number")
    parser.add_argument("--decision-file", help="Claude's structured output, as JSON")
    args = parser.parse_args(argv)

    raw_decision = None
    if args.decision_file:
        try:
            with open(args.decision_file, encoding="utf-8") as decision_file:
                raw_decision = decision_file.read()
        except FileNotFoundError:
            pass

    planned = plan(read_issue_state(args.issue), raw_decision)
    if planned.reasoning is not None:
        _log("reasoning", planned.reasoning)
    if planned.rejection is not None:
        _log(f"rejected, #{args.issue} left unchanged", planned.rejection)
    for operation in planned.operations:
        print(f"triage apply: {operation.describe()}")
    perform(planned.operations)


if __name__ == "__main__":
    main()
