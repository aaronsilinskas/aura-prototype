"""Tests for scripts.triage_apply: validating Claude's triage decision and applying it."""

import json
import re
import subprocess
from unittest.mock import patch

import pytest

from scripts.triage_apply import (
    CATEGORY_LABELS,
    DECISION_SCHEMA,
    MAX_COMMENT_LENGTH,
    STATE_LABELS,
    EditLabels,
    PostComment,
    TriagedIssue,
    main,
    perform,
    plan,
)

_ISSUE = 7
_AUTHOR = "reporter"


def _issue(*labels: str) -> TriagedIssue:
    return TriagedIssue(number=_ISSUE, author=_AUTHOR, labels=frozenset(labels))


_DROP = object()


def _decision(**overrides: object) -> str:
    decision: dict[str, object] = {
        "category": "enhancement",
        "state": "ready-for-human",
        "already_implemented": False,
        "evidence": "searched engine/ for a matching effect",
        "comment": "This needs a spec before anyone builds it.",
        "reasoning": "spans several modules",
    }
    decision.update(overrides)
    return json.dumps({key: value for key, value in decision.items() if value is not _DROP})


def _label_edits(issue: TriagedIssue, decision: str | None) -> list[EditLabels]:
    return [op for op in plan(issue, decision).operations if isinstance(op, EditLabels)]


def test_a_valid_decision_sets_its_category_and_swaps_needs_triage_for_its_state():
    edits = _label_edits(_issue("needs-triage"), _decision())

    assert edits == [
        EditLabels(
            _ISSUE,
            add=frozenset({"enhancement", "ready-for-human"}),
            remove=frozenset({"needs-triage"}),
        )
    ]


def test_a_category_that_disagrees_with_the_issues_replaces_it():
    edits = _label_edits(_issue("needs-triage", "bug"), _decision(category="enhancement"))

    assert edits[0].add >= {"enhancement"}
    assert "bug" in edits[0].remove


def test_a_needs_triage_decision_keeps_needs_triage_and_removes_every_other_state():
    issue = _issue("needs-triage", "needs-info", "ready-for-agent", "ready-for-human", "bug")

    edits = _label_edits(issue, _decision(category="bug", state="needs-triage"))

    assert edits == [
        EditLabels(
            _ISSUE,
            add=frozenset(),
            remove=frozenset({"needs-info", "ready-for-agent", "ready-for-human"}),
        )
    ]


def test_a_decision_the_labels_already_match_changes_no_labels():
    edits = _label_edits(
        _issue("needs-triage", "bug"), _decision(category="bug", state="needs-triage")
    )

    assert edits == []


def test_labels_outside_triage_are_never_added_or_removed():
    pipeline = {"idea", "spec", "wayfinder:map", "wayfinder:task", "wontfix"}

    edits = _label_edits(_issue("needs-triage", *pipeline), _decision())

    assert all(not (edit.add | edit.remove) & pipeline for edit in edits)


_DISCLAIMER = "> *This was generated by AI during triage.*"
_BRIEF = "Goal: add a fade effect.\n\nFiles: effects/fade.py"


def _comments(issue: TriagedIssue, decision: str | None) -> list[PostComment]:
    return [op for op in plan(issue, decision).operations if isinstance(op, PostComment)]


def test_a_valid_decision_posts_one_comment_of_the_disclaimer_then_the_decisions_comment():
    comments = _comments(_issue("needs-triage"), _decision(comment="Needs a spec."))

    assert comments == [PostComment(_ISSUE, f"{_DISCLAIMER}\n\nNeeds a spec.")]


def test_a_ready_for_agent_comment_ends_with_the_agent_brief():
    decision = _decision(state="ready-for-agent", comment="Small and clear.", agent_brief=_BRIEF)

    comments = _comments(_issue("needs-triage"), decision)

    assert [c.body for c in comments] == [f"{_DISCLAIMER}\n\nSmall and clear.\n\n{_BRIEF}"]


def _comment_body(decision: str) -> str:
    [comment] = _comments(_issue("needs-triage"), decision)
    return comment.body


def test_a_long_comment_is_capped_and_still_starts_with_the_disclaimer():
    body = _comment_body(_decision(comment="spam " * MAX_COMMENT_LENGTH))

    assert len(body) <= MAX_COMMENT_LENGTH
    assert body.startswith(_DISCLAIMER)


def test_a_long_agent_brief_is_capped_too():
    decision = _decision(state="ready-for-agent", agent_brief="brief " * MAX_COMMENT_LENGTH)

    assert len(_comment_body(decision)) <= MAX_COMMENT_LENGTH


def _mentions(body: str) -> set[str]:
    """The logins GitHub would notify: an @ that follows no word character, then a login."""
    return set(re.findall(r"(?<![\w`])@([A-Za-z0-9][A-Za-z0-9-]*)", body))


def test_mentions_other_than_the_author_are_neutralised():
    body = _comment_body(_decision(comment="cc @someone, @org/team and @Other-User please"))

    assert _mentions(body) == set()


def test_a_mention_of_the_author_still_notifies_them_whatever_its_case():
    body = _comment_body(_decision(comment="@Reporter can you share the log? cc @someone"))

    assert _mentions(body) == {"Reporter"}


def test_mentions_in_the_agent_brief_are_neutralised_too():
    decision = _decision(state="ready-for-agent", agent_brief="Ask @someone first.")

    assert _mentions(_comment_body(decision)) == set()


def test_an_email_address_is_left_as_written():
    body = _comment_body(_decision(comment="Mail dev@example.com."))

    assert "Mail dev@example.com." in body


