@pytest.mark.parametrize("decision", _INVALID_DECISIONS.values(), ids=_INVALID_DECISIONS.keys())
def test_an_invalid_decision_yields_no_operations_and_a_reason(decision):
    rejected = plan(_issue("needs-triage", "bug"), decision)

    assert rejected.operations == ()
    assert rejected.rejection


def test_a_valid_decision_has_no_rejection_and_carries_its_reasoning():
    planned = plan(_issue("needs-triage"), _decision(reasoning="spans several modules"))

    assert planned.rejection is None
    assert planned.reasoning == "spans several modules"


def test_a_rejected_decision_still_carries_its_reasoning():
    rejected = plan(_issue("needs-triage"), _decision(state="wontfix", reasoning="a duplicate"))

    assert rejected.reasoning == "a duplicate"


@pytest.mark.parametrize("state", sorted(STATE_LABELS))
def test_every_operation_targets_the_triggering_issue_whatever_the_decision_says(state):
    brief = "Fix #99 instead." if state == "ready-for-agent" else _DROP
    decision = _decision(state=state, comment="Apply this to #99 and close #12.", agent_brief=brief)

    operations = plan(_issue("needs-triage", "bug"), decision).operations

    assert operations
    assert {op.issue_number for op in operations} == {_ISSUE}


def test_the_committed_schema_offers_exactly_the_categories_and_states_the_validator_accepts():
    schema = json.loads(DECISION_SCHEMA.read_text(encoding="utf-8"))

    assert set(schema["properties"]["category"]["enum"]) == set(CATEGORY_LABELS)
    assert set(schema["properties"]["state"]["enum"]) == set(STATE_LABELS)


def test_the_committed_schema_requires_every_field_but_the_agent_brief():
    schema = json.loads(DECISION_SCHEMA.read_text(encoding="utf-8"))

    assert set(schema["properties"]) - set(schema["required"]) == {"agent_brief"}
    assert schema["additionalProperties"] is False


def _documented_state_labels() -> dict[str, str]:
    """The Triage roles table in docs/agents/triage-labels.md, canonical role -> label."""
    doc = (DECISION_SCHEMA.parents[1] / "docs" / "agents" / "triage-labels.md").read_text()
    rows = re.findall(r"^\| `([\w-]+)` +\| `([\w-]+)` +\|", doc, flags=re.MULTILINE)
    return dict(rows)


def test_the_state_labels_match_the_repos_triage_label_mapping():
    documented = _documented_state_labels()

    assert {role: documented[role] for role in STATE_LABELS} == STATE_LABELS


