class _FakeGh:
    """Stands in for ``subprocess.run`` as ``gh``: answers ``issue view`` with one issue."""

    def __init__(self, labels=("needs-triage",), author=_AUTHOR) -> None:
        self.calls: list[list[str]] = []
        self.stdin: list[str | None] = []
        self._issue = {
            "author": {"login": author},
            "labels": [{"name": name, "color": "ffffff"} for name in labels],
        }

    def __call__(self, args, **kwargs):
        self.calls.append(list(args))
        self.stdin.append(kwargs.get("input"))
        stdout = json.dumps(self._issue) if args[:3] == ["gh", "issue", "view"] else ""
        return subprocess.CompletedProcess(args, 0, stdout=stdout, stderr="")

    @property
    def writes(self) -> list[list[str]]:
        return [call for call in self.calls if call[:3] != ["gh", "issue", "view"]]


def test_perform_posts_a_comment_on_the_issue_with_the_body_on_stdin():
    fake_gh = _FakeGh()

    with patch("scripts.triage_apply.subprocess.run", fake_gh):
        perform([PostComment(42, "--body is not a flag here")])

    assert fake_gh.calls == [["gh", "issue", "comment", "42", "--body-file", "-"]]
    assert fake_gh.stdin == ["--body is not a flag here"]


def test_perform_edits_the_issues_labels_in_one_call():
    fake_gh = _FakeGh()
    edit = EditLabels(42, add=frozenset({"bug", "needs-info"}), remove=frozenset({"needs-triage"}))

    with patch("scripts.triage_apply.subprocess.run", fake_gh):
        perform([edit])

    [call] = fake_gh.calls
    assert call[:4] == ["gh", "issue", "edit", "42"]
    assert sorted(zip(call[4::2], call[5::2])) == [
        ("--add-label", "bug"),
        ("--add-label", "needs-info"),
        ("--remove-label", "needs-triage"),
    ]


def _run_step(tmp_path, fake_gh, decision: str | None, issue: int = 42) -> None:
    args = ["--issue", str(issue)]
    if decision is not None:
        decision_file = tmp_path / "decision.json"
        decision_file.write_text(decision, encoding="utf-8")
        args += ["--decision-file", str(decision_file)]
    with patch("scripts.triage_apply.subprocess.run", fake_gh):
        main(args)


def test_the_step_reads_the_live_issue_then_comments_and_relabels_it(tmp_path):
    fake_gh = _FakeGh(labels=("needs-triage", "spec"))

    _run_step(tmp_path, fake_gh, _decision(category="bug", state="needs-info"))

    assert fake_gh.calls[0][:4] == ["gh", "issue", "view", "42"]
    assert [call[:4] for call in fake_gh.writes] == [
        ["gh", "issue", "comment", "42"],
        ["gh", "issue", "edit", "42"],
    ]


def test_the_step_lets_the_live_author_keep_their_mention(tmp_path):
    fake_gh = _FakeGh(author="octo")

    _run_step(tmp_path, fake_gh, _decision(comment="@octo which board? cc @someone"))

    [body] = [text for text in fake_gh.stdin if text is not None]
    assert _mentions(body) == {"octo"}


@pytest.mark.parametrize(
    "decision", [None, "", _decision(state="wontfix")], ids=["no file", "empty", "wontfix"]
)
def test_the_step_writes_nothing_for_an_invalid_or_missing_decision(tmp_path, decision):
    fake_gh = _FakeGh()

    _run_step(tmp_path, fake_gh, decision)

    assert fake_gh.writes == []


def test_the_step_logs_the_reasoning_and_the_rejection(tmp_path, capsys):
    _run_step(tmp_path, _FakeGh(), _decision(state="wontfix", reasoning="looks like a duplicate"))

    log = capsys.readouterr().out
    assert "looks like a duplicate" in log
    assert "'wontfix'" in log


def test_the_step_logs_the_reasoning_of_a_valid_decision(tmp_path, capsys):
    _run_step(tmp_path, _FakeGh(), _decision(reasoning="spans several modules"))

    assert "spans several modules" in capsys.readouterr().out


def test_the_step_keeps_decision_text_on_one_log_line_so_it_cannot_issue_workflow_commands(
    tmp_path, capsys
):
    _run_step(tmp_path, _FakeGh(), _decision(reasoning="fine\n::error::injected"))

    assert not any(line.startswith("::") for line in capsys.readouterr().out.splitlines())
